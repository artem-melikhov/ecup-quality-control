QUESTION = "Вопрос: этот товар легковоспламеняющийся? Ответь одним словом: да или нет."


def build_messages(item: dict, fewshot: list, desc_limit: int = 700, fs_desc_limit: int = 160) -> list:
    """item: {name, desc, subcat}; fewshot: [{name, desc, label}] из train-фолдов той же подкатегории."""
    sub = item.get("subcat", "Прочее")
    system = SYSTEM_BASE + "\n\n" + SUBCAT_INSTRUCTIONS.get(sub, SUBCAT_INSTRUCTIONS["Прочее"])

    parts = []
    if fewshot:
        parts.append("Примеры разметки в этой подкатегории:")
        for ex in fewshot:
            ans = "да" if ex["label"] == 1 else "нет"
            d = (ex.get("desc") or "")[:fs_desc_limit].replace("\n", " ")
            parts.append(f"- {ex['name']} || {d} -> {ans}")
        parts.append("")
    parts.append("Товар для оценки:")
    parts.append(f"Название: {item['name']}")
    parts.append(f"Описание: {(item.get('desc') or '')[:desc_limit]}")
    parts.append("")
    parts.append(QUESTION)

    return [{"role": "system", "content": system},
            {"role": "user", "content": "\n".join(parts)}]
